/**
 * Generate `server.py` — JSON-RPC dispatcher + typed stubs for the manifest
 * functions. The user implements only the function bodies.
 */
export function generatePythonServer(manifest: NativeManifest): string {
  const lines: string[] = [];
  lines.push(`#!/usr/bin/env python3`);
  lines.push(`# Auto-generated by AsiJS — DO NOT EDIT the dispatcher below.`);
  lines.push(`# Implement the function bodies, then run your app: the interpreter`);
  lines.push(`# is spawned automatically and speaks JSON-RPC over stdio.`);
  lines.push(``);
  lines.push(`import base64`);
  lines.push(`import json`);
  lines.push(`import sys`);
  lines.push(``);
  lines.push(``);
  for (const fn of manifest.functions) {
    const params = Object.entries(fn.params)
      .map(([n]) => safeIdent(n, PY_KEYWORDS))
      .join(", ");
    lines.push(`def ${safeIdent(fn.name, PY_KEYWORDS)}(${params}):`);
    lines.push(`    # TODO: implement the body of ${fn.name}`);
    lines.push(`    raise NotImplementedError("implement ${fn.name}")`);
    lines.push(``);
    lines.push(``);
  }
  lines.push(`_PARAM_TYPES = {`);
  lines.push(paramTypesTable(manifest, (n, t) => `"${n}": "${t}"`));
  lines.push(`}`);
  lines.push(``);
  lines.push(`_RETURN_TYPES = {`);
  lines.push(returnTypesTable(manifest, (t) => `"${t}"`));
  lines.push(`}`);
  lines.push(``);
  lines.push(`_HANDLERS = {`);
  for (const fn of manifest.functions) {
    lines.push(`    "${fn.name}": ${safeIdent(fn.name, PY_KEYWORDS)},`);
  }
  lines.push(`}`);
  lines.push(``);
  lines.push(``);
  lines.push(`def _coerce_args(fn_name, args):`);
  lines.push(`    """Decode wire values: bytes params arrive as base64 strings."""`);
  lines.push(`    types = _PARAM_TYPES.get(fn_name, {})`);
  lines.push(`    out = {}`);
  lines.push(`    for key, value in args.items():`);
  lines.push(`        if types.get(key) == "bytes":`);
  lines.push(`            out[key] = base64.b64decode(value) if isinstance(value, str) else value`);
  lines.push(`        else:`);
  lines.push(`            out[key] = value`);
  lines.push(`    return out`);
  lines.push(``);
  lines.push(``);
  lines.push(`def _coerce_result(fn_name, value):`);
  lines.push(`    """Encode a bytes result as a base64 string for the wire."""`);
  lines.push(`    if _RETURN_TYPES.get(fn_name) == "bytes":`);
  lines.push(`        if isinstance(value, (bytes, bytearray, memoryview)):`);
  lines.push(`            return base64.b64encode(bytes(value)).decode("ascii")`);
  lines.push(`    return value`);
  lines.push(``);
  lines.push(``);
  lines.push(`def _main():`);
  lines.push(`    for line in sys.stdin:`);
  lines.push(`        line = line.strip()`);
  lines.push(`        if not line:`);
  lines.push(`            continue`);
  lines.push(`        req_id = None`);
  lines.push(`        try:`);
  lines.push(`            req = json.loads(line)`);
  lines.push(`            req_id = req.get("id")`);
  lines.push(`            handler = _HANDLERS.get(req.get("fn"))`);
  lines.push(`            if handler is None:`);
  lines.push(`                raise ValueError("unknown function: %s" % req.get("fn"))`);
  lines.push(`            args = req.get("args") or {}`);
  lines.push(`            result = handler(**_coerce_args(req.get("fn"), args))`);
  lines.push(`            sys.stdout.write(json.dumps({`);
  lines.push(`                "id": req_id, "ok": True,`);
  lines.push(`                "result": _coerce_result(req.get("fn"), result),`);
  lines.push(`            }) + "\\n")`);
  lines.push(`        except Exception as exc:  # noqa: BLE001 — report, keep serving`);
  lines.push(`            sys.stdout.write(json.dumps({`);
  lines.push(`                "id": req_id, "ok": False, "error": str(exc),`);
  lines.push(`            }) + "\\n")`);
  lines.push(`        sys.stdout.flush()`);
  lines.push(``);
  lines.push(``);
  lines.push(`if __name__ == "__main__":`);
  lines.push(`    _main()`);
  lines.push(``);
  return lines.join("\n");
}

