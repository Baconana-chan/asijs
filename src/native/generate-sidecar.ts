/**
 * Generate `server.rb` — JSON-RPC dispatcher + typed stubs.
 */
export function generateRubyServer(manifest: NativeManifest): string {
  const lines: string[] = [];
  lines.push(`#!/usr/bin/env ruby`);
  lines.push(`# Auto-generated by AsiJS — implement the function bodies, keep the dispatcher.`);
  lines.push(`require "json"`);
  lines.push(`require "base64"`);
  lines.push(``);
  lines.push(``);
  for (const fn of manifest.functions) {
    // Ruby 3 splits kwargs from positional args — the dispatcher calls
    // `handler.call(**args)`, so stubs must declare keyword params (`a:`).
    const params = Object.entries(fn.params)
      .map(([n]) => `${safeIdent(n, RB_KEYWORDS)}:`)
      .join(", ");
    lines.push(`def ${safeIdent(fn.name, RB_KEYWORDS)}(${params})`);
    lines.push(`  # TODO: implement the body of ${fn.name}`);
    // RuntimeError (not NotImplementedError) — it's a StandardError, so the
    // dispatcher's `rescue StandardError` catches it and reports via JSON.
    lines.push(`  raise "implement ${fn.name}"`);
    lines.push(`end`);
    lines.push(``);
    lines.push(``);
  }
  lines.push(`PARAM_TYPES = {`);
  lines.push(paramTypesTable(manifest, (n, t) => `"${n}" => "${t}"`, (fnName, params) => `"${fnName}" => { ${params} }`));
  lines.push(`}.freeze`);
  lines.push(``);
  lines.push(`RETURN_TYPES = {`);
  lines.push(returnTypesTable(manifest, (t) => `"${t}"`, (fnName, value) => `"${fnName}" => ${value}`));
  lines.push(`}.freeze`);
  lines.push(``);
  lines.push(`HANDLERS = {`);
  for (const fn of manifest.functions) {
    lines.push(`  "${fn.name}" => method(:${safeIdent(fn.name, RB_KEYWORDS)}),`);
  }
  lines.push(`}.freeze`);
  lines.push(``);
  lines.push(``);
  lines.push(`def coerce_args(fn_name, args)`);
  lines.push(`  # Decode wire values: bytes params arrive as base64 strings.`);
  lines.push(`  types = PARAM_TYPES[fn_name] || {}`);
  lines.push(`  args.each_with_object({}) do |(key, value), out|`);
  lines.push(`    out[key] = types[key] == "bytes" ? Base64.decode64(value) : value`);
  lines.push(`  end`);
  lines.push(`end`);
  lines.push(``);
  lines.push(``);
  lines.push(`def coerce_result(fn_name, value)`);
  lines.push(`  # Encode a binary String result as a base64 string for the wire.`);
  lines.push(`  if RETURN_TYPES[fn_name] == "bytes" && value.is_a?(String) && value.encoding == Encoding::BINARY`);
  lines.push(`    Base64.strict_encode64(value)`);
  lines.push(`  else`);
  lines.push(`    value`);
  lines.push(`  end`);
  lines.push(`end`);
  lines.push(``);
  lines.push(``);
  lines.push(`STDOUT.sync = true`);
  lines.push(``);
  lines.push(`STDIN.each_line do |line|`);
  lines.push(`  line = line.strip`);
  lines.push(`  next if line.empty?`);
  lines.push(`  req_id = nil`);
  lines.push(`  begin`);
  lines.push(`    req = JSON.parse(line)`);
  lines.push(`    req_id = req["id"]`);
  lines.push(`    handler = HANDLERS[req["fn"]]`);
  lines.push(`    raise "unknown function: \#{req["fn"]}" unless handler`);
  lines.push(`    args = coerce_args(req["fn"], req["args"] || {}).transform_keys(&:to_sym)`);
  lines.push(`    result = handler.call(**args)`);
  lines.push(`    STDOUT.puts(JSON.generate({ "id" => req_id, "ok" => true, "result" => coerce_result(req["fn"], result) }))`);
  lines.push(`  rescue StandardError => e`);
  lines.push(`    STDOUT.puts(JSON.generate({ "id" => req_id, "ok" => false, "error" => e.message }))`);
  lines.push(`  end`);
  lines.push(`end`);
  lines.push(``);
  return lines.join("\n");
}

