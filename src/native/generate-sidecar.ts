/**
 * Native / Polyglot Modules — sidecar server generators (2.2)
 *
 * Interpreted languages (Python/Ruby/PHP) run as sidecar processes: AsiJS
 * spawns the interpreter with a generated `server.<ext>` script and speaks
 * JSON-RPC over stdio (one JSON object per line). The user implements only
 * the function bodies; the dispatcher, param-type tables and bytes
 * (de)serialization are generated from the manifest.
 *
 * Wire format: plain JSON. `bytes` values travel as base64 strings — the
 * manifest types tell the script exactly which params/results are bytes,
 * so no marker objects leak into user code.
 */

import type { NativeManifest, NativeTypeName } from "./manifest";
import { tsTypeName } from "./manifest";

// ============================================================================
// Identifier safety (reserved words per language)
// ============================================================================

const PY_KEYWORDS = new Set([
  "False", "None", "True", "and", "as", "assert", "async", "await", "break",
  "class", "continue", "def", "del", "elif", "else", "except", "finally",
  "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
  "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
]);

const RB_KEYWORDS = new Set([
  "alias", "and", "begin", "break", "case", "class", "def", "defined?", "do",
  "else", "elsif", "end", "ensure", "false", "for", "if", "in", "module",
  "next", "nil", "not", "or", "redo", "rescue", "retry", "return", "self",
  "super", "then", "true", "undef", "unless", "until", "when", "while",
  "yield", "BEGIN", "END", "__FILE__", "__LINE__",
]);

const PHP_KEYWORDS = new Set([
  "abstract", "and", "array", "as", "break", "callable", "case", "catch",
  "class", "clone", "const", "continue", "declare", "default", "do", "echo",
  "else", "elseif", "empty", "enddeclare", "endfor", "endforeach", "endif",
  "endswitch", "endwhile", "enum", "eval", "exit", "extends", "final",
  "finally", "fn", "for", "foreach", "function", "global", "goto", "if",
  "implements", "include", "include_once", "instanceof", "insteadof",
  "interface", "isset", "list", "match", "namespace", "new", "or", "print",
  "private", "protected", "public", "readonly", "require", "require_once",
  "return", "static", "switch", "throw", "trait", "try", "unset", "use",
  "var", "while", "xor", "yield",
]);

/** Make an identifier safe for a language's reserved words. */
function safeIdent(name: string, keywords: Set<string>): string {
  return keywords.has(name) ? `${name}_` : name;
}

/** Build the param-type table lines for a language. */
function paramTypesTable(
  manifest: NativeManifest,
  fmt: (name: string, type: NativeTypeName) => string,
  wrap: (fnName: string, params: string) => string = (fnName, params) => `"${fnName}": { ${params} }`,
): string {
  return manifest.functions
    .map((fn) => {
      const params = Object.entries(fn.params)
        .map(([n, t]) => fmt(n, t))
        .join(", ");
      return `    ${wrap(fn.name, params)},`;
    })
    .join("\n");
}

/** Build the return-type table lines. */
function returnTypesTable(
  manifest: NativeManifest,
  fmt: (type: NativeTypeName) => string,
  wrap: (fnName: string, value: string) => string = (fnName, value) => `"${fnName}": ${value}`,
): string {
  return manifest.functions
    .map((fn) => `    ${wrap(fn.name, fmt(fn.returns))},`)
    .join("\n");
}

