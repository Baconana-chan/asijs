/**
 * Generate `server.php` — JSON-RPC dispatcher + typed stubs.
 */
export function generatePhpServer(manifest: NativeManifest): string {
  const lines: string[] = [];
  lines.push(`<?php`);
  lines.push(`// Auto-generated by AsiJS — implement the function bodies, keep the dispatcher.`);
  lines.push(`declare(strict_types=1);`);
  lines.push(``);
  lines.push(``);
  for (const fn of manifest.functions) {
    const params = Object.entries(fn.params)
      .map(([n]) => `$${safeIdent(n, PHP_KEYWORDS)}`)
      .join(", ");
    lines.push(`function ${safeIdent(fn.name, PHP_KEYWORDS)}(${params}) {`);
    lines.push(`    // TODO: implement the body of ${fn.name}`);
    lines.push(`    throw new RuntimeException("implement ${fn.name}");`);
    lines.push(`}`);
    lines.push(``);
    lines.push(``);
  }
  lines.push(`$PARAM_TYPES = [`);
  lines.push(paramTypesTable(manifest, (n, t) => `"${n}" => "${t}"`, (fnName, params) => `"${fnName}" => [ ${params} ]`));
  lines.push(`];`);
  lines.push(``);
  lines.push(`$RETURN_TYPES = [`);
  lines.push(returnTypesTable(manifest, (t) => `"${t}"`, (fnName, value) => `"${fnName}" => ${value}`));
  lines.push(`];`);
  lines.push(``);
  lines.push(`$HANDLERS = [`);
  for (const fn of manifest.functions) {
    lines.push(`    "${fn.name}" => "${safeIdent(fn.name, PHP_KEYWORDS)}",`);
  }
  lines.push(`];`);
  lines.push(``);
  lines.push(``);
  lines.push(`function coerce_args(string $fnName, array $args): array {`);
  lines.push(`    $types = $GLOBALS["PARAM_TYPES"][$fnName] ?? [];`);
  lines.push(`    foreach ($args as $key => $value) {`);
  lines.push(`        if (($types[$key] ?? null) === "bytes") {`);
  lines.push(`            $args[$key] = base64_decode((string) $value);`);
  lines.push(`        }`);
  lines.push(`    }`);
  lines.push(`    return $args;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(``);
  lines.push(`function coerce_result(string $fnName, $value) {`);
  lines.push(`    if (($GLOBALS["RETURN_TYPES"][$fnName] ?? null) === "bytes") {`);
  lines.push(`        return base64_encode((string) $value);`);
  lines.push(`    }`);
  lines.push(`    return $value;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(``);
  lines.push(`while (($line = fgets(STDIN)) !== false) {`);
  lines.push(`    $line = trim($line);`);
  lines.push(`    if ($line === "") { continue; }`);
  lines.push(`    $reqId = null;`);
  lines.push(`    try {`);
  lines.push(`        $req = json_decode($line, true);`);
  lines.push(`        $reqId = $req["id"] ?? null;`);
  lines.push(`        $fn = $req["fn"] ?? null;`);
  lines.push(`        if (!is_string($fn) || !array_key_exists($fn, $GLOBALS["HANDLERS"])) {`);
  lines.push(`            throw new RuntimeException("unknown function: " . $fn);`);
  lines.push(`        }`);
  lines.push(`        $args = coerce_args($fn, $req["args"] ?? []);`);
  lines.push(`        $result = call_user_func_array($GLOBALS["HANDLERS"][$fn], $args);`);
  lines.push(`        fwrite(STDOUT, json_encode([`);
  lines.push(`            "id" => $reqId, "ok" => true,`);
  lines.push(`            "result" => coerce_result($fn, $result),`);
  lines.push(`        ]) . "\\n");`);
  lines.push(`    } catch (Throwable $e) {`);
  lines.push(`        fwrite(STDOUT, json_encode(["id" => $reqId, "ok" => false, "error" => $e->getMessage()]) . "\\n");`);
  lines.push(`    }`);
  lines.push(`    fflush(STDOUT);`);
  lines.push(`}`);
  lines.push(``);
  return lines.join("\n");
}

